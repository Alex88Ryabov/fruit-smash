let currentLang = 'ru';

function detectLang() {
  const saved = localStorage.getItem('fruktolet.lang');
  if (saved && STRINGS[saved]) {
    return saved;
  }
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  if (nav === 'uk') {
    return 'uk';
  }
  if (nav === 'ru' || nav === 'be' || nav === 'kk') {
    return 'ru';
  }
  return 'en';
}

function t(key, params) {
  const dict = STRINGS[currentLang] || STRINGS.en;
  let value = dict[key];
  if (value === undefined) {
    value = STRINGS.en[key];
  }
  if (value === undefined) {
    return key;
  }
  if (!params) {
    return value;
  }
  return value.replace(/\{(\w+)\}/g, (match, name) => (params[name] !== undefined ? params[name] : match));
}

// подписи в html-разметке проставляются по data-i18n, чтобы не дублировать строки
function applyDomStrings() {
  document.documentElement.lang = currentLang;
  document.title = t('doc.title');
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    node.innerHTML = t(node.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
}

function setLang(lang) {
  if (!STRINGS[lang]) {
    return;
  }
  currentLang = lang;
  localStorage.setItem('fruktolet.lang', lang);
  applyDomStrings();
}

function getLang() {
  return currentLang;
}

currentLang = detectLang();
